const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
Module._extensions['.ts'] = (module, filename) => {
  const output=ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}});
  module._compile(output.outputText,filename);
};
const { TUTORIALS, TUTORIAL_BY_LEVEL, tutorialAvailable } = require('../src/game/tutorials.ts');
const { tutorialScopeKey, readSeen, markSeen } = require('../src/game/tutorialProgress.ts');
const { LEVEL_ORDER } = require('../src/game/levels.ts');
assert.deepEqual(TUTORIALS.map(t=>t.level),['pumpHouse','primePump','prismTower','oasisRelay','saltSealedIntake','saltboundHinges','marketArrival','seedStore']);
assert.equal(new Set(TUTORIALS.map(t=>t.id)).size,8);
for(const t of TUTORIALS){assert.equal(TUTORIAL_BY_LEVEL[t.level],t);assert.ok(LEVEL_ORDER.includes(t.level));assert.ok(t.stages.length>=4);}
const memory=new Map();
const store={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
const guest={kind:'guest'}, accountA={kind:'account',accountId:'alpha'}, accountB={kind:'account',accountId:'beta'}, sandbox={kind:'sandbox'};
markSeen(guest,'jet',store);markSeen(accountA,'prism',store);markSeen(sandbox,'seedpod',store);
assert.deepEqual([...readSeen(guest,store)],['jet']);assert.deepEqual([...readSeen(accountA,store)],['prism']);
assert.deepEqual([...readSeen(accountB,store)],[]);assert.deepEqual([...readSeen(sandbox,store)],['seedpod']);
assert.notEqual(tutorialScopeKey(accountA),tutorialScopeKey(accountB));
store.setItem(tutorialScopeKey(accountB),JSON.stringify({version:1,seen:['jet','bogus','prism',4]}));
assert.deepEqual([...readSeen(accountB,store)],['jet','prism']);
store.setItem(tutorialScopeKey(accountB),'{bad');assert.deepEqual([...readSeen(accountB,store)],['jet','prism']);
const blocked={getItem(){throw new Error('denied')},setItem(){throw new Error('denied')}};
markSeen({kind:'account',accountId:'offline'},'flywheel',blocked);
assert.deepEqual([...readSeen({kind:'account',accountId:'offline'},blocked)],['flywheel']);
const stale={getItem(){return JSON.stringify({version:1,seen:['jet']})},setItem(){throw new Error('quota')}};
markSeen({kind:'account',accountId:'quota'},'prism',stale);
assert.deepEqual([...readSeen({kind:'account',accountId:'quota'},stale)],['jet','prism'],'quota fallback survives a subsequent read');
const seed=TUTORIALS.find(t=>t.id==='seedpod'), jet=TUTORIALS.find(t=>t.id==='jet');
assert.equal(tutorialAvailable(seed,[],null,false,false,new Set(['seedpod'])),false,'local preference never unlocks Farmland');
assert.equal(tutorialAvailable(seed,['seedStore'],null,true),true);
assert.equal(tutorialAvailable(seed,[],null,false,true),true,'sandbox library may preview all');
assert.equal(tutorialAvailable(jet,[],null,false),false);
assert.equal(tutorialAvailable(jet,[],'pumpHouse',false),true);
assert.equal(tutorialAvailable(jet,['pumpHouse'],null,false),true);
assert.equal(tutorialAvailable(jet,[],null,false,false,new Set(['jet'])),true);
console.log('Eight tutorial mappings, chapter gate, scope isolation, validation, and blocked-storage fallback passed.');
