const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const Module=require('node:module');
Module._extensions['.ts']=(module,filename)=>module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,filename);
const {createPuzzle,playTurn,resolveAction}=require('../src/game/core.ts');
const {CONDENSATION_LEVEL}=require('../src/game/experiments/condensation.ts');
const route=require('./fixtures/condensation-winning-route.json');
const cell=(row,col)=>({row,col});
const firstClear=turn=>turn.steps.find(step=>step.kind==='clear');
const coordinates=cells=>cells.map(({row,col})=>`${row},${col}`).sort();
const base=()=>{
  const puzzle=createPuzzle(CONDENSATION_LEVEL);
  puzzle.board=Array.from({length:9},(_,row)=>Array.from({length:9},(_,col)=>({id:row*9+col+1,kind:puzzle.symbols[(row*2+col)%puzzle.symbols.length]})));
  puzzle.board[4][2].kind='gear';
  return puzzle;
};
const wetMatch=base();
wetMatch.board[4][3].kind='water';wetMatch.board[4][4].kind='gear';wetMatch.board[4][5].kind='water';wetMatch.board[3][4].kind='water';
const matched=playTurn(wetMatch,cell(3,4),cell(4,4));
assert(matched.valid);
assert.deepEqual(coordinates(firstClear(matched).spread),['4,3','4,5']);
assert.equal(matched.state.condensation.wet[4][4],true);
assert.equal(wetMatch.condensation.wet[4][3],false,'input terrain is immutable');
assert.equal(firstClear(matched).goals.condensation,20);
assert.equal(firstClear(matched).wet[4][3],true,'clear step captures the wet terrain');
const disconnected=base();
disconnected.board[4][3].kind='water';disconnected.board[4][4].kind='gear';disconnected.board[4][5].kind='water';disconnected.board[3][4].kind='water';
for(const col of [2,3,4])disconnected.board[2][col].kind='leaf';
const separate=playTurn(disconnected,cell(3,4),cell(4,4));
assert(separate.valid);
assert.deepEqual(coordinates(firstClear(separate).spread),['4,3','4,5'],'a dry disconnected match does not spread');
const dryPower=base();dryPower.board[4][2].jet='row';
const dryFire=playTurn(dryPower,cell(4,2),cell(4,2));
assert(dryFire.valid);assert.equal(firstClear(dryFire).spread.length,0,'a dry row beam crossing the wet collector at 4,4 remains dry');
const created=base();
for(const col of [3,4,5])created.board[4][col].kind='water';
created.board[4][6].kind='gear';created.board[4][7].kind='gear';created.board[3][6].kind='water';
const creation=playTurn(created,cell(3,6),cell(4,6));
assert(creation.valid);
assert.deepEqual(coordinates(firstClear(creation).spread),['4,3','4,5','4,6'],'wet match includes the initially dry power creation square');
assert.equal(firstClear(creation).board[4][6].jet,'row','new power remains on the wet collector');
assert.equal(creation.stats.powersActivated.jet,0,'newly created power does not fire in its creation wave');
const wetPower=base();wetPower.board[4][4].jet='row';
const wetFire=playTurn(wetPower,cell(4,4),cell(4,4));
assert(wetFire.valid);
assert.deepEqual(coordinates(firstClear(wetFire).spread),['4,2','4,3','4,5','4,6'],'a wet jet coats every collector it hits');
const sealed=base();sealed.board[4][4].jet='row';sealed.board[4][5]=null;sealed.crust[4][5]=2;sealed.goals.crust=1;
const sealedHit=playTurn(sealed,cell(4,4),cell(4,4));
assert(sealedHit.valid);assert.equal(firstClear(sealedHit).crust[4][5],1);
assert.equal(firstClear(sealedHit).wet[4][5],false,'remaining salt layer blocks wet collector spread');
assert(!coordinates(firstClear(sealedHit).spread).includes('4,5'));
const lastSeal=base();lastSeal.board[4][4].jet='row';lastSeal.board[4][5]=null;lastSeal.crust[4][5]=1;lastSeal.goals.crust=1;
const freed=playTurn(lastSeal,cell(4,4),cell(4,4));
assert(freed.valid);assert.equal(firstClear(freed).crust[4][5],0);
assert.equal(firstClear(freed).wet[4][5],true,'wet-origin direct hit coats a net when it removes the last salt layer');
assert.equal(lastSeal.condensation.wet[4][5],false,'salt/wet resolution does not mutate the previous state');
const adjacentSeal=base();adjacentSeal.board[4][3].kind='water';adjacentSeal.board[4][4].kind='gear';adjacentSeal.board[4][5].kind='water';adjacentSeal.board[3][4].kind='water';adjacentSeal.board[4][6]=null;adjacentSeal.crust[4][6]=1;adjacentSeal.goals.crust=1;
const adjacentFreed=playTurn(adjacentSeal,cell(3,4),cell(4,4));
assert(adjacentFreed.valid);assert.equal(firstClear(adjacentFreed).crust[4][6],0);
assert.equal(firstClear(adjacentFreed).wet[4][6],true,'wet match coats the neighboring net when its salt seal breaks');
const alreadyWet=base();alreadyWet.condensation.wet[4][3]=true;alreadyWet.goals.condensation--;
alreadyWet.board[4][4].jet='row';
const repeat=playTurn(alreadyWet,cell(4,4),cell(4,4));
assert(repeat.valid);
assert.deepEqual(coordinates(firstClear(repeat).spread),['4,2','4,5','4,6'],'already wet collectors receive no duplicate credit');
const dryChain=base();dryChain.board[4][4].jet='row';dryChain.board[4][2].jet='column';
const chained=playTurn(dryChain,cell(4,4),cell(4,4));
assert(chained.valid);
assert.deepEqual(coordinates(firstClear(chained).spread),['4,2','4,3','4,5','4,6'],'the newly wet dry jet cannot spread down its column in the same wave');
const combo=base();combo.board[4][3].jet='row';combo.board[4][4].jet='column';
const combined=playTurn(combo,cell(4,3),cell(4,4));
assert(combined.valid);assert(firstClear(combined).spread.length>=4,'either wet combo origin qualifies the combined footprint');
const dryPrism=base();dryPrism.board[2][2].power='prism';
const dryPrismTurn=playTurn(dryPrism,cell(2,2),cell(2,2));
assert(dryPrismTurn.valid);assert.equal(firstClear(dryPrismTurn).spread.length,0,'a dry Prism selecting tiles beyond wet terrain does not spread');
const wetPrism=base();wetPrism.board[4][4].power='prism';
const wetPrismTurn=playTurn(wetPrism,cell(4,4),cell(4,4));
assert(wetPrismTurn.valid);assert(firstClear(wetPrismTurn).spread.length>0,'a wet Prism coats selected collector squares');
const prismCombo=base();prismCombo.board[4][4].power='prism';prismCombo.board[4][3].jet='row';
const prismComboTurn=playTurn(prismCombo,cell(4,3),cell(4,4));
assert(prismComboTurn.valid);assert(prismComboTurn.steps.some(step=>step.kind==='convert'));
assert(firstClear(prismComboTurn).spread.length>=4,'a wet Prism combo coats its converted target footprint');
const bomb=resolveAction(wetMatch,{kind:'tileBomb',target:cell(3,3)});
assert(bomb.valid);assert.equal(firstClear(bomb).spread.length,0,'single tile bomb does not spread');
let puzzle=createPuzzle(CONDENSATION_LEVEL);
assert.equal(puzzle.currents,undefined);
assert.equal(puzzle.condensation.collectors.flat().filter(Boolean).length,25);
assert.equal(puzzle.condensation.wet.flat().filter(Boolean).length,3);
for(const [from,to] of route){const turn=playTurn(puzzle,from,to);assert(turn.valid);puzzle=turn.state;}
assert.equal(puzzle.status,'won','authored nine-move route fills all collectors');
assert.equal(puzzle.goals.condensation,0);
assert.equal(puzzle.moves,17);
let finalMove=createPuzzle(CONDENSATION_LEVEL);
for(const [from,to] of route.slice(0,-1)){const turn=playTurn(finalMove,from,to);assert(turn.valid);finalMove=turn.state;}
finalMove.moves=1;
const last=playTurn(finalMove,...route.at(-1));
assert.equal(last.state.status,'won','the last move wins when it coats the final collectors');
assert.equal(last.state.moves,0);
console.log('Condensation checks passed: wet matches, dry matches, powers, chain snapshot, bomb isolation, and a no-booster win.');
