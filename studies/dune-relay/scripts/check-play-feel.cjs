    const initialStats = await stats();
    await page.waitForFunction(() => Boolean(document.querySelector('canvas')?.dataset.idleHint), { timeout: 10000 });
    assert.equal(await page.locator('.frame').getAttribute('data-moves'), initial, 'hint does not use a move');
    assert.deepEqual(await stats(), initialStats, 'hint does not change playtest moves, goals, or totals');
