    await page.waitForTimeout(5500);
    assert.equal(await page.locator('canvas').getAttribute('data-idle-hint'), null, 'settings pauses hint');
    await page.getByRole('button', { name: 'Close' }).click();
    await page.waitForFunction(() => Boolean(document.querySelector('canvas')?.dataset.idleHint), { timeout: 10000 });
    const pair = (await page.locator('canvas').getAttribute('data-idle-hint')).split(':').map(value => value.split(',').map(Number));
    const box = await page.locator('canvas').boundingBox();
    const from = { x: box.x + box.width / 2 + (330 + (pair[0][1] + .5) * 50 - 480) * box.height / 540, y: box.y + (45 + (pair[0][0] + .5) * 50) * box.height / 540 };
    await page.mouse.click(from.x, from.y);
    assert.equal(await page.locator('canvas').getAttribute('data-idle-hint'), null, 'pointer input cancels hint immediately');
    assert.equal(await page.locator('.frame').getAttribute('data-moves'), initial, 'hint cancellation does not use a move');
    await page.mouse.click(from.x, from.y); // Clear selection; the cue can run again.
    await page.waitForFunction(() => Boolean(document.querySelector('canvas')?.dataset.idleHint), { timeout: 10000 });
    const secondPair = (await page.locator('canvas').getAttribute('data-idle-hint')).split(':').map(value => value.split(',').map(Number));
    const toPoint = ([row, col]) => ({ x: box.x + box.width / 2 + (330 + (col + .5) * 50 - 480) * box.height / 540, y: box.y + (45 + (row + .5) * 50) * box.height / 540 });
    const a = toPoint(secondPair[0]), b = toPoint(secondPair[1]);
    await page.mouse.move(a.x, a.y); await page.mouse.down(); await page.mouse.move(b.x, b.y, { steps: 2 }); await page.mouse.up();
    await page.waitForFunction(initial => document.querySelector('.frame')?.dataset.moves === String(Number(initial) - 1), initial, { timeout: 20000 });
    assert.equal(await page.locator('canvas').getAttribute('data-idle-hint'), null, 'swipe cancels the hint');
    assert.equal((await stats()).movesUsed, initialStats.movesUsed + 1, 'mid-hint swipe commits exactly one move');
    const movesAfterSwipe = await page.locator('.frame').getAttribute('data-moves');
    const held = toPoint([3, 3]), dragged = toPoint([3, 4]);
    await page.mouse.move(held.x, held.y); await page.mouse.down();
    await page.evaluate(() => document.querySelector('button[aria-label=Settings]').click());
    await page.getByRole('button', { name: 'Close' }).waitFor();
    await page.mouse.move(dragged.x, dragged.y); await page.mouse.up();
    assert.equal(await page.locator('.frame').getAttribute('data-moves'), movesAfterSwipe, 'captured pointer cannot spend a move while Settings is open');
    await page.getByRole('button', { name: 'Close' }).click();
    console.log('Idle hint is nonmutating, pauses in Settings, a mid-hint swipe commits one move, and a captured pointer is cancelled by Settings.');
