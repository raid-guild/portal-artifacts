    await page.getByRole('button', { name: /Enter the oasis/ }).click();
    await page.locator('.awning-wipe').waitFor({ state: 'detached' });
    const mapBox = await page.locator('canvas').boundingBox();
    const mapScale = mapBox.width / 960, mapTop = 540 - mapBox.height / mapScale;
    await page.mouse.click(mapBox.x + 465 * mapScale, mapBox.y + (367 - mapTop) * mapScale);
    await page.getByRole('button', { name: /Let's do it/ }).waitFor({ timeout: 15000 });
