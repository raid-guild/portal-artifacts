const assert=require('node:assert/strict');
const fs=require('node:fs');
const ts=require('typescript');
const Module=require('node:module');
Module._extensions['.ts']=(module,filename)=>module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,filename);
const {LEVEL_ORDER}=require('../src/game/levels.ts');
const {EMPTY_SAVE}=require('../src/game/save.ts');
const {chapterReplayReady,replayAllowed,replayDestinations}=require('../src/game/chapterReplay.ts');
const nine={...EMPTY_SAVE,completed:LEVEL_ORDER.slice(0,9)};
const ten={...EMPTY_SAVE,completed:LEVEL_ORDER.slice(0,10)};
assert.equal(chapterReplayReady(nine,'oasis',false),false);
assert.deepEqual(replayDestinations(nine,'oasis',false),[]);
assert.equal(chapterReplayReady(ten,'oasis',false),true);
assert.equal(replayAllowed(ten,'pumpHouse',false),true);
assert.deepEqual(replayDestinations(ten,'oasis',false)[0].levels,LEVEL_ORDER.slice(0,4));
assert.equal(replayDestinations(ten,'oasis',false).length,7);
const all={...EMPTY_SAVE,completed:[...LEVEL_ORDER]};
assert.equal(chapterReplayReady(all,'farmland',false),false);
assert.equal(chapterReplayReady(all,'farmland',true),true);
assert.equal(replayAllowed(all,'seedStore',false),false);
assert.equal(replayDestinations(all,'farmland',true).length,10);
const campaignAccess={farmland:true,town:true,castle:true};
const castleLevels=LEVEL_ORDER.filter(id=>require('../src/game/levels.ts').LEVELS[id].chapter==='castle');
assert.equal(castleLevels.length,10,'Castle Island has ten levels');
assert.equal(chapterReplayReady(all,'castle',campaignAccess),true);
assert.equal(replayDestinations(all,'castle',campaignAccess).flatMap(group=>group.levels).length,10,'completed Castle exposes all ten replay levels');
assert.equal(chapterReplayReady(all,'castle',{...campaignAccess,castle:false}),false,'inactive Dune Pass hides Castle replay');
assert.deepEqual(replayDestinations(all,'castle',{...campaignAccess,castle:false}),[]);
const partialCastle={...all,completed:LEVEL_ORDER.filter(id=>id!==castleLevels[9])};
assert.equal(chapterReplayReady(partialCastle,'castle',campaignAccess),false,'partial Castle cannot open chapter replay');
assert.deepEqual(replayDestinations(partialCastle,'castle',campaignAccess),[]);
const mapSource=fs.readFileSync(require('node:path').resolve(__dirname,'../src/game/GameCanvas.tsx'),'utf8');
const oasisHandler=mapSource.slice(mapSource.indexOf('function makeMapScene('),mapSource.indexOf('function makeCaravanScene('));
assert.match(oasisHandler,/if \(this\.locked\) return;\s*props\.audio\?\.unlock\(\);\s*const replay = replayPoints\.find/,'Oasis ignores rapid repeated marker taps before starting another replay walk');
console.log('Replay eligibility and destination grouping checks passed.');
